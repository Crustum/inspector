<?php

declare(strict_types=1);

use Crustum\Inspector\Scanners\YarnPackageLock;

it('scans yarn v1 lockfiles', function (): void {
    $base = fixtureCopy([
        'cake-app/package.json' => 'package.json',
        'cake-app/yarn-v1.lock' => 'yarn.lock',
    ]);

    $packages = (new YarnPackageLock($base))->scan();

    $quickLru = inspectorCollection($packages)->first(fn ($p): bool => $p->name() === '@alloc/quick-lru');
    expect($quickLru)->not->toBeNull();
    expect($quickLru->version())->toEqual('5.2.0');

    $cliui = inspectorCollection($packages)->first(fn ($p): bool => $p->name() === '@isaacs/cliui');
    expect($cliui)->not->toBeNull();
    expect($cliui->version())->toEqual('8.0.2');

    cleanup($base);
});

